def note(rels, unit, extra=""):
    a, b = rels[0], rels[-1]
    if a is b:
        span = f"{md(a['published'])} 발표({md(a['reference_date'])} 기준)"
    else:
        span = f"{md(a['published'])}~{md(b['published'])} 발표 {len(rels)}건(조사 기준 주를 이어 붙임, 겹치는 주의 값이 발표 사이에 고쳐진 칸 0)"
