def validate(pack):
    errs = []
    feed = {s: D.live(s) for s in D.CX}
    mine = {b["payload"]["post"]["external_id"] for b in pack["bundles"]}
    by_day = defaultdict(list)
    for b in pack["bundles"]:
        by_day[b["payload"]["post"]["published_at"][:10]].append(b)
    for d, bs in sorted(by_day.items()):
        sub = {"bundles": bs, "comments": []}
        for e in D.validate(sub, d):
            if "관점 댓글 0개" in e:
                continue
            errs.append(f"{d}: {e}")
        # 시차 — 하루치 검사는 11/4 글부터라 여기서 건다
        mine_t = [datetime.fromisoformat(b["payload"]["post"]["published_at"]) for b in bs]
        others = [datetime.fromisoformat(i["published_at"].replace("Z", "+00:00")).astimezone(D.KST)
                  for s in feed for e, i in feed[s].items() if B.kst_day(i["published_at"]) == d and e not in mine]
        for t in mine_t:
            if t.minute % 5 == 0:
                errs.append(f"{d} {t:%H:%M}: 분이 5의 배수")
            for u in mine_t + others:
                if u is not t and abs((u - t).total_seconds()) <= D.MIN_GAP * 60:
                    errs.append(f"{d} {t:%H:%M} · {u:%H:%M}: {D.MIN_GAP}분 이내")
    for b in pack["bundles"]:
        po = b["payload"]["post"]
        tag = po["external_id"]
        t = po["published_at"]
        for s in po["sources"]:
            m = re.search(r"(\d+)월 (\d+)일 발표", s["label"])
            pub = f"2026-{int(m.group(1)):02d}-{int(m.group(2)):02d}"
            if REL[pub]["embargo_kst"] > t:
                errs.append(f"{tag}: 보도 전 인용 {pub}")
        for m in re.finditer(r"(\d+)월 (\d+)일", po["source_note"]):
            if f"2026-{int(m.group(1)):02d}-{int(m.group(2)):02d}" > t[:10]:
                errs.append(f"{tag}: 확인 기준 칸에 게시일 뒤 날짜")
        if re.search(r"소급|작성\)|조회 20|확인 20|11월", po["source_note"] + po["body"]):
            errs.append(f"{tag}: 작성 시점이 드러나는 표기")
        if re.search(r"오를|내릴 것|오를 것|전망|예상|반등할|하락할|상승할", po["body"]):
            errs.append(f"{tag}: 예측·전망 어휘 '{re.search(r'오를|내릴 것|오를 것|전망|예상|반등할|하락할|상승할', po['body']).group()}'")
        if mono_run(po["body"]) >= 4:
            errs.append(f"{tag}: '~니다.' {mono_run(po['body'])}연속")
        if not re.search(r"단지[^.?!]{0,12}(값|숫자|이야기|기록|답안지|눈금|성적표|칸|누계|거리)|한 단지", po["body"]):
            errs.append(f"{tag}: 구 지수가 단지 값이 아니라는 문장 없음")
    trans = []
    for b in pack["bundles"]:
        t = [s for s in D.sentences(b["payload"]["post"]["body"]) if TRANSITION.search(s)]
        if not t:
            errs.append(f"{b['payload']['post']['external_id']}: 사실/해석 전환 문장 없음")
        trans += t[:1]
    dup = [k for k, v in Counter(trans).items() if v > 1]
    if dup:
        errs.append(f"팩 안 같은 전환 문장 {dup}")
    titles = [b["payload"]["post"]["title"] for b in pack["bundles"]]
    if len(set(titles)) != len(titles):
        errs.append("제목 중복")
    per = Counter(b["payload"]["post"]["persona_external_id"] for b in pack["bundles"])
    months = defaultdict(set)
    for b in pack["bundles"]:
        months[b["payload"]["post"]["persona_external_id"]].add(b["payload"]["post"]["published_at"][5:7])
    for k, n in per.items():
        if n != 3 or months[k] != {"08", "09", "10"}:
            errs.append(f"{k}: 8·9·10월 한 편씩이 아님 {sorted(months[k])}")
    return errs


def main():
    pack = build()
    for b in pack["bundles"]:
        x = b["payload"]["post"]
        print(f"  {x['published_at'][:16]}  {x['complex_external_id']:24}{x['persona_external_id']:24}{len(x['title']):>2}자  {x['title']}")
    errs = validate(pack)
    if errs:
        print("자체 검증 실패:", *errs, sep="\n  - ", file=sys.stderr)
        return 1
    for b in pack["bundles"]:
        b.pop("_series")
        b.pop("_fn")
    OUT.write_text(json.dumps(pack, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"자체 검증 통과 {len(pack['bundles'])}편 → {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
